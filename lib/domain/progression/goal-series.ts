/** H18.2 — единый источник правила «как мерить прогресс к цели упражнения».
 *  Чистая функция (R-7): строит серию метрики из истории сессий упражнения.
 *  Раньше эта логика жила инлайн на /exercises/[id]; с reuse трек-бара на
 *  «Прошлый раз» активной тренировки появился второй потребитель → знание
 *  вынесено сюда, чтобы не разъехалось (DRY про знание, не про буквы). */

/** Минимальная структурная форма сессии истории упражнения. Намеренно НЕ
 *  импортируем ExerciseSession из repo — домен не зависит от адаптеров (R-7);
 *  stats.repo.ExerciseSession структурно совместим. */
export type GoalSeriesSession = {
  /** Лучший расчётный 1ПМ сессии (0, если рабочих сетов не было). */
  best1rm: number;
  sets: { setType: string; weightKg: number }[];
};

/** Серия значений метрики для трека цели по её виду.
 *  Вход — история «новые сверху» (как stats.repo.exerciseSetHistory);
 *  выход — хронологический старое→новое (порядок, который ждёт projectProgress).
 *  - `1rm`: лучший рабочий e1RM по сессии; сессии без рабочих сетов (best1rm=0)
 *    исключены, чтобы разминочные дни не давали ложный регресс.
 *  - `weight`: макс рабочего веса по сессии; сессии без рабочих сетов исключены;
 *    разминочные веса не учитываются. */
export function goalSeries(
  history: GoalSeriesSession[],
  kind: "weight" | "1rm",
): number[] {
  if (kind === "1rm") {
    return history
      .filter((s) => s.best1rm > 0)
      .map((s) => s.best1rm)
      .reverse();
  }
  return history
    .map((s) =>
      Math.max(
        0,
        ...s.sets
          .filter((x) => x.setType === "working")
          .map((x) => x.weightKg),
      ),
    )
    .filter((w) => w > 0)
    .reverse();
}
