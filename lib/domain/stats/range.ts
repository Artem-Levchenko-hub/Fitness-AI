/** Окна периода статистики `/stats`. Чистая доменная политика временного окна
 *  (R-7: домен не зависит от слоя БД) — единственный источник правды для набора
 *  допустимых диапазонов и их преобразования в дату-отсечку. Реэкспортится из
 *  `lib/repos/stats.repo` (для запросов) и переиспользуется доменом
 *  (`period-insight`) — раньше значения дублировались в обоих местах. */
export type StatsRange = "7d" | "30d" | "90d" | "365d" | "all";

/** Нижняя граница («от») окна: скользящее окно от ТЕКУЩЕГО момента на `range`
 *  дней назад. `"all"` → `null` (без фильтра по времени — все завершённые
 *  тренировки). Граница включительная (`>=` на стороне SQL-запроса). */
export function rangeToFromDate(range: StatsRange): Date | null {
  if (range === "all") return null;
  const days = parseInt(range, 10);
  return new Date(Date.now() - days * 24 * 60 * 60 * 1000);
}
