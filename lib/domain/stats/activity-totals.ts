/** Итоги активности за период — единица KPI «Подходы / Повторения / Тоннаж».
 *  Любой формат, где есть выполненные подходы, вносит вклад: силовые рабочие
 *  подходы И круговые невыполненные-пропуск раунды (раунд = подход). Кардио сюда
 *  не входит (нет подходов/веса) — оно отдельная размерность (минуты/сессии). */
export type ActivityTotals = {
  /** Число выполненных подходов: силовые working + круговые non-skipped раунды. */
  sets: number;
  /** Суммарные повторения этих подходов (круговой duration-раунд = 0 повторов). */
  reps: number;
  /** Тоннаж (вес·повторы) — там где есть вес. Bodyweight-подход = 0 тоннажа,
   *  но он всё равно считается подходом с повторами (честно, без инфляции). */
  tonnageKg: number;
};

const ZERO: ActivityTotals = { sets: 0, reps: 0, tonnageKg: 0 };

/** Складывает вклад каждого формата в общие KPI-итоги. ОДНО место знает «что
 *  считается подходом» (R-04 — знание, не буквы): добавить формат = добавить
 *  слагаемое, не править каждую метрику. Чистая функция (R-7) — node-юнит-тест
 *  с фикстурами силовые/круговые/смешанные/bodyweight-zero-tonnage. Решает баг
 *  «круговая тренировка → KPI 0 подходов» (противоречивая карточка /stats). */
export function combineActivityTotals(parts: ActivityTotals[]): ActivityTotals {
  return parts.reduce(
    (acc, p) => ({
      sets: acc.sets + p.sets,
      reps: acc.reps + p.reps,
      tonnageKg: acc.tonnageKg + p.tonnageKg,
    }),
    ZERO,
  );
}
