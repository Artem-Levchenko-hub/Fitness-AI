/** Перемешивает копию массива (Fisher–Yates). Вызывать ТОЛЬКО на клиенте (в
 *  эффекте) — иначе SSR/CSR дадут разный порядок и hydration рассинхрон. */
export function shuffleTips<T>(arr: readonly T[]): T[] {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const tmp = a[i]!;
    a[i] = a[j]!;
    a[j] = tmp;
  }
  return a;
}

