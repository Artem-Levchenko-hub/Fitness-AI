/**
 * H13.2/H13.3 — резолв ссылок «фактор жизни в разборе → его экран».
 *
 * Разбор (TrainerResultCard) показывает аспекты «Восстановление (сон)» и
 * «Питание (КБЖУ)» со score. Когда тренер реально учёл фактор (score != null),
 * заголовок аспекта становится входом в данные: «Восстановление» → /sleep,
 * «Питание» → /nutrition (как 3D-аватар, столп 2 — разбор сам ведёт к источнику).
 *
 * Граница (прецедент H6.2b): ссылки ТОЛЬКО на своём разборе. share /a/[token] и
 * разбор друга НЕ включают `enabled` → заголовок статичен (ссылка увела бы
 * смотрящего в ЕГО /sleep, не в данные автора разбора).
 *
 * Чистая (R-7): db/auth не импортит, принимает уже выбранные значения.
 */

/**
 * Путь к экрану фактора жизни для заголовка аспекта.
 * `null` (статичный заголовок), если:
 *  - `enabled` выключен (чужой/share-разбор — граница H6.2b), либо
 *  - `score == null` (фактор не учтён → нет данных, R-37: без битой ссылки на
 *    пустой экран).
 * `score === 0` — валидная оценка (фактор учтён) → ссылка показывается.
 */
export function resolveLifeFactorHref(
  href: string,
  score: number | null,
  enabled: boolean | undefined,
): string | null {
  if (!enabled) return null;
  if (score == null) return null;
  return href;
}
